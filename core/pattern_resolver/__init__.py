"""Zero-seed Steam signature resolvers.

Vendored from ``huanyuejue/steam-monitor`` (``tools/resolve_patterns.py``,
``tools/resolve_ipc.py``, ``tools/migrate_patterns.py``).  The upstream tools
are MIT-style community tooling; see the module docstrings for the original
algorithm notes.  Local modifications are limited to package-relative imports
and the small in-process wrappers below.

The resolvers take a Steam DLL and emit the exact TOML schemas consumed by
OpenSteamTool/ZSteamTool:

* ``pattern/<component>/<sha256>.toml`` — hook RVA + byte signature
* ``ipc/steamclient/<sha256>.toml`` — vtable RVA + wrapper RVA + wire constants

Resolution is strict: a wrong channel/constant set fails loudly instead of
guessing.  Callers may tolerate partial *pattern* output (missing hooks disable
gracefully in the kernel), but IPC output is all-or-nothing.
"""
from __future__ import annotations

from hashlib import sha256
from pathlib import Path

from . import resolve_ipc as _ipc
from . import resolve_patterns as _patterns


def resolve_pattern_entries(dll_path: str | Path, side: str) -> tuple[dict, list]:
    """Resolve hook patterns for one DLL.

    Returns ``(found, failed)`` where ``found`` maps hook name to
    ``(rva, signature)`` and ``failed`` is a list of ``(name, reason)``.
    """
    ctx = _patterns.Ctx(Path(dll_path))
    return _patterns.resolve(ctx, side)


def render_pattern_toml(found: dict) -> str:
    """Render resolved pattern entries in the kernel's TOML schema."""
    lines = [
        "# MACHINE-GENERATED by OpenSteamToolDesktop local pattern resolver\n",
        "# Vendored from huanyuejue/steam-monitor (zero-seed resolver).\n",
    ]
    for name, (rva, sig) in sorted(found.items()):
        lines += [
            f"[0x{_patterns.fnv1a(name):08X}]",
            f'name = "{name}"',
            f'rva = "0x{rva:X}"',
            f'sig = "{sig}"',
            "",
        ]
    return "\n".join(lines)


def write_pattern_toml(dll_path: str | Path, side: str, out_dir: str | Path) -> tuple[Path, list]:
    """Resolve and write ``pattern/<side>/<sha>.toml``.

    Partial output is written on purpose: ZSteamTool disables only the hooks
    whose entries are missing, which is far better than disabling the module.
    """
    dll_path = Path(dll_path)
    found, failed = resolve_pattern_entries(dll_path, side)
    if not found:
        raise RuntimeError(
            f"pattern resolver found no hooks for {side}: "
            + "; ".join(f"{n}: {r}" for n, r in failed[:4])
        )
    digest = sha256(dll_path.read_bytes()).hexdigest()
    target = Path(out_dir) / side / f"{digest}.toml"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render_pattern_toml(found), encoding="utf-8", newline="\n")
    return target, failed


def render_ipc_toml(dll_path: str | Path, channel: str) -> str:
    """Resolve the IPC table for one channel; raise on any failure."""
    dll_path = Path(dll_path)
    img = _patterns.mp.Image(dll_path)
    spans = _ipc.data_spans(img)
    if not spans:
        raise RuntimeError("IPC resolver: no data sections")
    base = _ipc.image_base(img.buf)
    pdata = set(sorted(img.pdata_entries()))
    resolved = []
    failed = []
    for iface, base_spec in _ipc.IPC_IFACES.items():
        spec = _ipc.channel_spec(iface, base_spec, channel)
        vt, methods, err = _ipc.resolve_iface(spec, img, spans, base, pdata)
        if err is not None:
            failed.append(f"{iface}: {err}")
        else:
            resolved.append((iface, spec, vt, methods))
    if failed:
        raise RuntimeError(f"IPC channel {channel} failed: " + "; ".join(failed))
    return _ipc.render_toml(resolved)


def write_ipc_toml(dll_path: str | Path, channel: str, out_dir: str | Path) -> Path:
    """Resolve and write ``ipc/steamclient/<sha>.toml``."""
    dll_path = Path(dll_path)
    text = render_ipc_toml(dll_path, channel)
    digest = sha256(dll_path.read_bytes()).hexdigest()
    target = Path(out_dir) / "steamclient" / f"{digest}.toml"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return target


__all__ = [
    "resolve_pattern_entries",
    "render_pattern_toml",
    "write_pattern_toml",
    "render_ipc_toml",
    "write_ipc_toml",
]
